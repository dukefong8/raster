(ns raster.compiler.valhalla-test
  (:require [clojure.test :refer [deftest is testing]]
            [raster.compiler.core.method-entry]
            [raster.compiler.backend.jvm.valhalla :as valhalla]))

(deftest valhalla-requires-preview-enabled
  (let [preview? (boolean
                  (some #{"--enable-preview"}
                        (.getInputArguments
                         (java.lang.management.ManagementFactory/getRuntimeMXBean))))]
    (when (>= (.feature (Runtime/version)) 27)
      (is (= preview? valhalla/valhalla-available?)))))

(deftest generated-value-class-targets-running-preview-jdk
  (when valhalla/valhalla-available?
    (testing "generated bytecode uses the running JDK's preview classfile version"
      (let [generate (ns-resolve 'raster.compiler.backend.jvm.valhalla
                                 'generate-value-class-bytes)
            bytes (generate "raster.compiler.GeneratedVersionProbe" [])
            buffer (doto (java.nio.ByteBuffer/wrap bytes)
                     (.position 4))
            minor (Short/toUnsignedInt (.getShort buffer))
            major (Short/toUnsignedInt (.getShort buffer))]
        (is (= 65535 minor))
        (is (= (+ 44 (.feature (Runtime/version))) major))))))
